"""Expands core/model/amd_mlfg_weights.xz (tools/mlfg_weights.py) into the C++ header the DLL embeds: the build step, Python
standard library only (docs/DESIGN.md D10). The header is generated, not kept in the repository.

    python tools/embed_weights.py IN.xz OUT.h
SPDX-License-Identifier: MIT
"""
import lzma, os, struct, sys

src, out = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
n = int.from_bytes(data[:4], 'little')
plane = lzma.decompress(data[4:])
h = len(plane) // 2
raw = bytearray(len(plane))
raw[0::2], raw[1::2] = plane[:h], plane[h:]
raw = bytes(raw[:n]) + b'\0' * (-n % 8)
words = struct.unpack(f'<{len(raw) // 8}Q', raw)
tmp = out + '.tmp'
with open(tmp, 'w') as f:
    f.write('// Generated by tools/embed_weights.py from core/model/amd_mlfg_weights.xz: AMD FSR Frame Generation 4\'s network\n'
            '// weights (AMD FidelityFX SDK v2.4.0, MIT; licenses/, docs/FFX_MLFG.md). Layout: tools/mlfg_weights.py.\n'
            '#pragma once\n#include <cstdint>\nnamespace nfrux::mlfg\n{\n')
    f.write(f'inline constexpr uint32_t kWeightBytes = {n};\ninline constexpr uint64_t kWeights[{len(words)}] = {{\n')
    for i in range(0, len(words), 8):
        f.write(','.join('0x%x' % x for x in words[i:i + 8]) + ',\n')
    f.write('};\n}  // namespace nfrux::mlfg\n')
os.replace(tmp, out)